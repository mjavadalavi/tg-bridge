"""Fake interactive Claude TUI for the tui transport tests: a stdlib-only stand-in that runs on a pseudo-terminal.

It takes the flags the bridge passes to the real TUI and draws only what the bridge reacts to: the folder trust
dialog when FAKE_TUI_TRUST=1 (FAKE_TUI_TRUST_REMOUNT=1 loses the first Down to a late redraw; FAKE_TUI_TRUST_DEAF=1
ignores Down; FAKE_TUI_TRUST_SPLIT=1 draws the first dialog in two writes, the cursor on 'No, exit' before the other
choice arrives; FAKE_TUI_TRUST_GLYPH_SPLIT=1 splits it right after the bare cursor glyph), and the prompt
glyph when ready. A bracketed paste followed by CR is one user turn. Each
turn writes its transcript lines in the real shape to <FAKE_TUI_CONFIG_DIR>/projects/<encoded cwd>/<session id>.jsonl.
The scenario comes from FAKE_TUI_SCENARIO (text, tool, two_blocks, permission, slow, slow_quiet, echo_only, api_error,
no_conversation, and the background ones bg_bash, bg_monitor, bg_agent, bg_wakeup). A background scenario starts its work
in the turn and ends the turn; a thread then writes the work's end (a task notification that starts a self turn, or the
wakeup's fire) once FAKE_TUI_BG_FLAG exists, or after FAKE_TUI_BG_SECONDS (default 0.5) when no flag is set, or when /exit
releases it. FAKE_TUI_EXIT_DEAF=1 ignores the first /exit typed while a wakeup is pending (spike S4).
'/exit' writes the three local-command lines the TUI writes for it, then exits 0. FAKE_TUI_FOLDER, when set, is the projects folder the transcript is written to
instead of the encoded cwd, as a TUI that keeps its transcript elsewhere would. A typed prompt's line has the origin of the
bridge's own prompts in a real transcript (turnOrigin 'sdk'); FAKE_TUI_PROMPT_ORIGIN=human gives it the interactive shape.
Like the real TUI, a space is drawn as a cursor move, so the stripped screen has no spaces in the resume error.

The script runs with -I, so it imports nothing from tg_bridge: the hook it runs is the one from --settings, as the real
TUI runs it. FAKE_TUI_ENV_OUT, when set, receives the child's environment as JSON before the first prompt.
FAKE_TUI_SIZE_OUT, when set, receives the terminal size of the child's pty as JSON {rows, cols}.
FAKE_TUI_WINCH_OUT, when set, gets one JSON {rows, cols} line for each SIGWINCH, with the size read at that moment.
"""

import json
import os
import re
import select
import signal
import subprocess
import sys
import termios
import threading
import time
import tty
import uuid

PASTE_START = b"\x1b[200~"
PASTE_END = b"\x1b[201~"
DOWN = b"\x1b[B"
GLYPH = "❯"  # the prompt glyph and the trust dialog's selection marker
BYPASS = "bypassPermissions"
NO_VALUE_FLAGS = frozenset({"--allow-dangerously-skip-permissions"})
REMOUNT_SECONDS = 0.03    # a late remount of the trust dialog redraws this long after the Down that caused it
BACKGROUND_SCENARIOS = frozenset({"bg_bash", "bg_monitor", "bg_agent", "bg_wakeup"})
BG_SECONDS = 0.5          # without FAKE_TUI_BG_FLAG, the background work ends this long after the turn
BG_TASK_IDS = {"bg_bash": "btx1", "bg_monitor": "mon1", "bg_agent": "agent1"}
BG_TOOL_ID = "tu_bg"
WAKE_PROMPT = "Reply with the single word AWAKE."
POLL_SECONDS = 0.05
FINISH_JOIN_SECONDS = 5.0
FINISH_SETTLE_SECONDS = 0.6  # the tail polls every 0.2 s: the end lines are read before the TUI exits
LOCAL_COMMAND_LINES = (
    "<local-command-caveat>Caveat: the messages below were generated by the user while running local commands.</local-command-caveat>",
    "<command-name>/exit</command-name>\n<command-message>exit</command-message>\n<command-args></command-args>",
    "<local-command-stdout>(no content)</local-command-stdout>",
)
TRUST_FOOTER = "Enter to confirm \u00b7 Esc to cancel"  # the real trust dialog keeps this footer after Enter
SPLIT_SECONDS = 0.3       # a split dialog's second half arrives this long after its first half
SLOW_SECONDS = 30.0       # the slow tool runs this long unless Esc arrives first
HOOK_SECONDS = 60.0       # a permission hook that never gets an answer is denied after this long
API_ERROR_TEXT = "API Error: Request rejected (429) - 6 Claude Code sessions working at once"
ZERO_USAGE = {"input_tokens": 0, "output_tokens": 0, "cache_read_input_tokens": 0, "cache_creation_input_tokens": 0}
MESSAGE_USAGE = {"input_tokens": 10, "output_tokens": 5, "cache_read_input_tokens": 100,
                 "cache_creation_input_tokens": 20}
NON_ALNUM = re.compile(r"[^A-Za-z0-9]")


def say(text: str) -> None:
    """One line on the terminal. Raw mode has no output translation, so the line ends with CR LF."""
    sys.stdout.write(text + "\r\n")
    sys.stdout.flush()


def parse_flags(argv: list[str]) -> dict[str, str]:
    """The value of each --flag. The bridge's flags all take one value except the ones in NO_VALUE_FLAGS."""
    values: dict[str, str] = {}
    i = 0
    while i < len(argv):
        flag = argv[i]
        if flag.startswith("--") and flag not in NO_VALUE_FLAGS and i + 1 < len(argv):
            values[flag] = argv[i + 1]
            i += 2
        else:
            i += 1
    return values


class Transcript:
    """Appends transcript lines the way the TUI does: one JSON object per line, flushed at once."""

    def __init__(self, path: str, sid: str, cwd: str) -> None:
        self.path = path
        self.sid = sid
        self.cwd = cwd
        self.lock = threading.Lock()  # the turn and the background thread both write

    def add(self, **fields: object) -> None:
        obj = {"isSidechain": False, "sessionId": self.sid, "cwd": self.cwd, "uuid": str(uuid.uuid4()),
               "timestamp": time.strftime("%Y-%m-%dT%H:%M:%S.000Z", time.gmtime()), **fields}
        with self.lock, open(self.path, "a", encoding="utf-8") as f:
            f.write(json.dumps(obj) + "\n")

    def assistant(self, msg_id: str, content: list, **fields: object) -> None:
        message = {"id": msg_id, "type": "message", "role": "assistant", "model": "fake", "content": content,
                   "usage": MESSAGE_USAGE}
        self.add(type="assistant", message=message, **fields)

    def tool_result(self, tool_id: str, text: str, is_error: bool, tool_use_result: dict | None = None) -> None:
        block = {"type": "tool_result", "tool_use_id": tool_id, "content": text, "is_error": is_error}
        extra = {} if tool_use_result is None else {"toolUseResult": tool_use_result}
        self.add(type="user", message={"role": "user", "content": [block]}, **extra)

    def finish(self, duration_ms: int = 1234, **extra: object) -> None:
        self.add(type="system", subtype="stop_hook_summary", hookCount=1, hookErrors=[], level="suggestion")
        self.add(type="system", subtype="turn_duration", durationMs=duration_ms, messageCount=4, **extra)
        self.add(type="last-prompt", lastPrompt="done")
        self.add(type="file-history-snapshot", messageId=str(uuid.uuid4()), snapshot={"trackedFileBackups": {}})

    def local_command_exit(self) -> None:
        """The lines the TUI writes for a typed /exit: local-command lines, which are never a prompt (no turnOrigin)."""
        for text in LOCAL_COMMAND_LINES:
            self.add(type="user", message={"role": "user", "content": text})


class Background:
    """The background work of the session: at most one thread writes its end. release() lets it finish now (used by /exit),
    so the end lines land before the TUI exits, as they would when the work completes in time."""

    def __init__(self) -> None:
        self._release = threading.Event()
        self._thread: threading.Thread | None = None

    def start(self, tr: Transcript, scenario: str) -> None:
        self._release = threading.Event()
        self._thread = threading.Thread(target=end_background, args=(tr, scenario, self._release), daemon=True)
        self._thread.start()

    def pending(self) -> bool:
        return self._thread is not None and self._thread.is_alive()

    def finish(self) -> None:
        self._release.set()
        if self._thread is not None:
            self._thread.join(FINISH_JOIN_SECONDS)
            time.sleep(FINISH_SETTLE_SECONDS)


def begin_background(tr: Transcript, scenario: str) -> None:
    """The turn's background call (a Bash or Monitor, a background Agent, a ScheduleWakeup), in the real shape: the call
    line and its start confirmation in toolUseResult."""
    if scenario == "bg_bash":
        call = {"type": "tool_use", "id": BG_TOOL_ID, "name": "Bash",
                "input": {"command": "sleep 25; echo BGDONE > bg.txt", "run_in_background": "true"}}
        result = {"backgroundTaskId": BG_TASK_IDS[scenario]}
    elif scenario == "bg_monitor":
        call = {"type": "tool_use", "id": BG_TOOL_ID, "name": "Monitor",
                "input": {"command": "until test -f flag.txt; do sleep 1; done", "persistent": False}}
        result = {"taskId": BG_TASK_IDS[scenario], "timeoutMs": 1800000, "persistent": False}
    elif scenario == "bg_agent":
        call = {"type": "tool_use", "id": BG_TOOL_ID, "name": "Agent",
                "input": {"description": "Reply AGENTOK", "prompt": "Reply with AGENTOK.", "run_in_background": "true"}}
        result = {"isAsync": True, "status": "async_launched", "agentId": BG_TASK_IDS[scenario]}
    else:  # bg_wakeup
        call = {"type": "tool_use", "id": BG_TOOL_ID, "name": "ScheduleWakeup",
                "input": {"delaySeconds": 60, "noop": False, "prompt": WAKE_PROMPT}}
        result = {"scheduledFor": int(time.time() * 1000) + 60000, "clampedDelaySeconds": 60, "wasClamped": False}
    tr.assistant("msg_1", [call])
    tr.tool_result(BG_TOOL_ID, "started in the background", False, result)


def notification(task_id: str) -> str:
    return (f"<task-notification>\n<task-id>{task_id}</task-id>\n<tool-use-id>{BG_TOOL_ID}</tool-use-id>\n"
            "<status>completed</status>\n<summary>done</summary>\n</task-notification>")


def end_background(tr: Transcript, scenario: str, release: threading.Event) -> None:
    """Waits for the background work to finish, then writes its end: the wakeup's fire and its scheduled turn, or the task
    notification and the turn it starts. The turn ends with turn_duration like any other."""
    flag = os.environ.get("FAKE_TUI_BG_FLAG", "")
    seconds = float("inf") if flag else float(os.environ.get("FAKE_TUI_BG_SECONDS", str(BG_SECONDS)))
    deadline = time.monotonic() + seconds
    while not release.is_set() and time.monotonic() < deadline and not (flag and os.path.exists(flag)):
        release.wait(POLL_SECONDS)
    if scenario == "bg_wakeup":
        tr.add(type="system", subtype="scheduled_task_fire", taskId="wake1", prompt=WAKE_PROMPT)
        tr.add(type="user", isMeta=True, turnOrigin="scheduled", message={"role": "user", "content": WAKE_PROMPT})
        tr.assistant("msg_2", [{"type": "text", "text": "AWAKE"}])
    else:
        text = notification(BG_TASK_IDS[scenario])
        tr.add(type="queue-operation", operation="enqueue", content=text)
        tr.add(type="queue-operation", operation="dequeue")
        tr.add(type="user", message={"role": "user", "content": text}, turnOrigin="task_notification",
               origin={"kind": "task-notification"})
        tr.assistant("msg_2", [{"type": "text", "text": "FINISHED"}])
    tr.finish()


def read_keys(timeout: float | None) -> bytes:
    """The bytes waiting on the terminal, after at most timeout seconds (None waits for them). b'' when none came."""
    ready, _, _ = select.select([0], [], [], timeout)
    if not ready:
        return b""
    data = os.read(0, 4096)
    if not data:  # the terminal closed: the TUI ends with it
        sys.exit(0)
    return data


def next_token(buf: bytes) -> tuple[str, str, int] | None:
    """(kind, text, consumed) for the first key or paste in buf, or None when more bytes are needed to tell."""
    if not buf:
        return None
    if buf.startswith(PASTE_START):
        end = buf.find(PASTE_END, len(PASTE_START))
        if end < 0:
            return None
        return "paste", buf[len(PASTE_START):end].decode("utf-8", "replace"), end + len(PASTE_END)
    if PASTE_START.startswith(buf):
        return None  # a prefix of a paste start: the rest is still on its way
    if buf.startswith(b"\r"):
        return "cr", "", 1
    return "key", "", 1


def wait_for_esc(seconds: float) -> bool:
    """True when Esc arrives within seconds. Other keys are read and dropped, as the TUI does during a tool run."""
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        if b"\x1b" in read_keys(0.05):
            return True
    return False


def ask_hook(flags: dict[str, str], sid: str, cwd: str, transcript: str, tool_input: dict) -> dict:
    """Runs the PermissionRequest hook from --settings, as the TUI does. Returns its decision, or a deny if it fails."""
    settings = json.loads(flags["--settings"])
    command = settings["hooks"]["PermissionRequest"][0]["hooks"][0]["command"]
    payload = {"session_id": sid, "transcript_path": transcript, "cwd": cwd, "hook_event_name": "PermissionRequest",
               "permission_mode": flags.get("--permission-mode", ""), "tool_name": "Bash", "tool_input": tool_input,
               "permission_suggestions": [{"type": "addRules", "behavior": "allow", "destination": "session",
                                           "rules": [{"toolName": "Bash", "ruleContent": "echo *"}]}]}
    say("Do you want to proceed?")
    try:
        proc = subprocess.run(command, shell=True, input=json.dumps(payload), capture_output=True, text=True,
                              timeout=HOOK_SECONDS)
        lines = [line for line in proc.stdout.splitlines() if line.strip()]
        return json.loads(lines[-1])["hookSpecificOutput"]["decision"]
    except (subprocess.SubprocessError, ValueError, KeyError, IndexError):
        return {"behavior": "deny", "message": "no decision from the hook"}


def prompt_origin_fields() -> dict[str, object]:
    """The origin fields of a typed prompt's line. The default is the shape the bridge's own prompts have in a real
    transcript (turnOrigin 'sdk', entrypoint 'sdk-cli', no origin key). FAKE_TUI_PROMPT_ORIGIN=human writes the shape of
    an interactive terminal prompt instead (turnOrigin 'human' and origin {'kind': 'human'})."""
    if os.environ.get("FAKE_TUI_PROMPT_ORIGIN") == "human":
        return {"turnOrigin": "human", "origin": {"kind": "human"}}
    return {"turnOrigin": "sdk", "entrypoint": "sdk-cli"}


def run_turn(tr: Transcript, text: str, scenario: str, flags: dict[str, str], bg: Background) -> bool:
    """Writes one turn's transcript lines. False when the turn was interrupted (it then has no turn_duration)."""
    tr.add(type="user", promptId=str(uuid.uuid4()), message={"role": "user", "content": text},
           **prompt_origin_fields())
    tool = {"type": "tool_use", "id": "tu_1", "name": "Bash", "input": {"command": "echo hi"}}
    if scenario == "echo_only":  # the TUI read the prompt and wrote nothing else until Esc: the prompt line is the only echo
        if wait_for_esc(SLOW_SECONDS):
            say("Interrupted")
            return False
        tr.finish()
        return True
    if scenario == "tool":
        tr.assistant("msg_1", [{"type": "text", "text": "Running it."}])
        tr.assistant("msg_1", [tool])  # the same message id on a second line: the usage must count once
        tr.tool_result("tu_1", "hi", False)
    elif scenario == "permission":
        tr.assistant("msg_1", [tool])
        if flags.get("--permission-mode") == BYPASS:
            decision = {"behavior": "allow"}  # the TUI never asks in bypass, so it never runs the hook
        else:
            decision = ask_hook(flags, tr.sid, tr.cwd, tr.path, tool["input"])
        if decision.get("behavior") == "allow":
            tr.tool_result("tu_1", "hi", False)
        else:
            tr.tool_result("tu_1", str(decision.get("message") or ""), True)
    elif scenario == "two_blocks":
        tr.assistant("msg_1", [{"type": "text", "text": "FIRST"}])
        tr.assistant("msg_1", [{"type": "text", "text": "SECOND"}])  # the same message id, a second block
        tr.finish()
        return True
    elif scenario in ("slow", "slow_quiet"):
        tr.assistant("msg_1", [dict(tool, input={"command": "sleep 60"})])
        if wait_for_esc(SLOW_SECONDS):
            if scenario == "slow":  # quiet: the TUI writes nothing on Esc, so the bridge's fallback must end the turn
                tr.tool_result("tu_1", "[Request interrupted by user for tool use]", True)
            say("Interrupted")
            return False
        tr.tool_result("tu_1", "slept", False)
    elif scenario == "api_error":
        tr.assistant("msg_e", [{"type": "text", "text": API_ERROR_TEXT}], isApiErrorMessage=True,
                     error="rate_limit")
        tr.finish()
        return True
    elif scenario in BACKGROUND_SCENARIOS:
        begin_background(tr, scenario)
        tr.assistant("msg_1", [{"type": "text", "text": "STARTED"}])
        if scenario == "bg_agent":
            tr.finish(pendingBackgroundAgentCount=1)  # the TUI counts the background agent it left running
        else:
            tr.finish()
        bg.start(tr, scenario)
        return True
    else:  # text, and any scenario this fake does not know
        tr.assistant("msg_1", [{"type": "text", "text": "ANSWER"}])
        tr.finish()
        return True
    tr.assistant("msg_2", [{"type": "text", "text": "DONE"}])
    tr.finish()
    return True


def draw_trust_dialog(selected: int, split: bool = False) -> None:
    """Draws the folder trust dialog with the cursor on the choice selected (0 = No, exit; 1 = Yes). With split, the
    dialog stops after the cursor on 'No, exit' and the 'Yes' choice is drawn SPLIT_SECONDS later."""
    say("Quick safety check: Is this a project you created or one you trust?")
    say(f"{GLYPH} No, exit" if selected == 0 else "  No, exit")
    if split:
        time.sleep(SPLIT_SECONDS)
    say(f"{GLYPH} Yes, I trust this folder" if selected == 1 else "  Yes, I trust this folder")
    say(TRUST_FOOTER)


def draw_trust_dialog_split_after_glyph() -> None:
    """Draws the dialog in two writes. The first ends right after the bare cursor glyph, so a read between the two sees a
    prompt glyph with no choice after it; the choices and the key hint come SPLIT_SECONDS later."""
    sys.stdout.write("Quick safety check: Is this a project you created or one you trust?" + GLYPH)
    sys.stdout.flush()
    time.sleep(SPLIT_SECONDS)
    say(" No, exit")
    say("  Yes, I trust this folder")
    say(TRUST_FOOTER)


def show_trust_dialog(remount: bool, deaf: bool, split: bool, glyph_split: bool) -> None:
    """Draws the folder trust dialog. Enter on the first choice exits 1; Down and then Enter continues. With deaf, Down
    does nothing. With remount, the first Down draws the cursor on Yes and then, REMOUNT_SECONDS later, redraws the dialog
    with the cursor back on No, as the live TUI did while it was still mounting: that Down is lost."""
    selected = 0
    if glyph_split:
        draw_trust_dialog_split_after_glyph()
    else:
        draw_trust_dialog(selected, split)
    remounted = False
    while True:
        data = read_keys(None)
        if DOWN in data and not deaf:
            if remount and not remounted:
                remounted = True
                draw_trust_dialog(1)
                time.sleep(REMOUNT_SECONDS)
                draw_trust_dialog(0)
            else:
                selected = 1
                draw_trust_dialog(1)
        if b"\r" in data:
            if selected == 0:
                sys.exit(1)
            return


def show_external_dialog() -> None:
    """Draws the external imports dialog with the cursor on 'No, disable external imports' (its default) and waits for Esc,
    the dialog's cancel. Other keys are read and dropped, as the live dialog drops them."""
    say("External imports: /home/fake/.claude/RTK.md Important: Only use Claude Code with files you trust")
    say(f"{GLYPH} No, disable external imports")
    say("  Yes, allow external imports")
    say("Enter to confirm \u00b7 Esc to cancel")
    while b"\x1b" not in read_keys(None):
        pass


def show_unknown_dialog() -> None:
    """Draws a selection dialog the bridge does not know, and keeps every key: the dialog never ends by itself."""
    say("Pick a model for this session")
    say(f"{GLYPH} Sonnet")
    say("  Opus")
    say("Enter to confirm \u00b7 Esc to cancel")
    while True:
        read_keys(None)


def log_winch(path: str) -> None:
    """A SIGWINCH: the terminal size of the pty at that moment is appended to path as one JSON line."""
    size = os.get_terminal_size(sys.stdin.fileno())
    with open(path, "a", encoding="utf-8") as f:
        f.write(json.dumps({"rows": size.lines, "cols": size.columns}) + "\n")


def main() -> None:
    flags = parse_flags(sys.argv[1:])
    resuming = "--resume" in flags
    sid = flags.get("--session-id") or flags.get("--resume") or "fake-sid"
    scenario = os.environ.get("FAKE_TUI_SCENARIO", "text")
    cwd = os.getcwd()
    folder = os.environ.get("FAKE_TUI_FOLDER") or NON_ALNUM.sub("-", os.path.realpath(cwd))
    transcript = os.path.join(os.environ["FAKE_TUI_CONFIG_DIR"], "projects", folder, sid + ".jsonl")
    if os.environ.get("FAKE_TUI_ENV_OUT"):
        with open(os.environ["FAKE_TUI_ENV_OUT"], "w", encoding="utf-8") as f:
            json.dump(dict(os.environ), f)
    if os.environ.get("FAKE_TUI_SIZE_OUT"):
        size = os.get_terminal_size(sys.stdin.fileno())
        with open(os.environ["FAKE_TUI_SIZE_OUT"], "w", encoding="utf-8") as f:
            json.dump({"rows": size.lines, "cols": size.columns}, f)
    if os.environ.get("FAKE_TUI_WINCH_OUT"):
        signal.signal(signal.SIGWINCH, lambda *_: log_winch(os.environ["FAKE_TUI_WINCH_OUT"]))
    try:
        tty.setraw(0)  # the keys arrive as typed: no echo, no line editing
    except termios.error:
        pass
    if scenario == "no_conversation" and resuming:
        message = f"No conversation found with session ID: {sid}"
        sys.stdout.write(message.replace(" ", "\x1b[1C") + "\r\n")  # cursor moves, not spaces, as the real TUI draws it
        sys.stdout.flush()
        sys.exit(1)
    if os.environ.get("FAKE_TUI_TRUST") == "1":
        show_trust_dialog(remount=os.environ.get("FAKE_TUI_TRUST_REMOUNT") == "1",
                          deaf=os.environ.get("FAKE_TUI_TRUST_DEAF") == "1",
                          split=os.environ.get("FAKE_TUI_TRUST_SPLIT") == "1",
                          glyph_split=os.environ.get("FAKE_TUI_TRUST_GLYPH_SPLIT") == "1")
    if os.environ.get("FAKE_TUI_EXTERNAL") == "1":
        show_external_dialog()
    if os.environ.get("FAKE_TUI_UNKNOWN") == "1":
        show_unknown_dialog()
    os.makedirs(os.path.dirname(transcript), exist_ok=True)
    tr = Transcript(transcript, sid, cwd)
    bg = Background()
    deaf = os.environ.get("FAKE_TUI_EXIT_DEAF") == "1"
    exit_ignored = False
    say(f"{GLYPH} ")
    buf = b""
    typed: str | None = None
    while True:
        buf += read_keys(None)
        while True:
            token = next_token(buf)
            if token is None:
                break
            kind, text, used = token
            buf = buf[used:]
            if kind == "paste":
                typed = (typed or "") + text
            elif kind == "cr" and typed is not None:
                message, typed = typed, None
                if os.environ.get("FAKE_TUI_SWALLOW") == "1":  # the keys went to a dialog: no transcript line is written
                    continue
                if message.strip() == "/exit":
                    if deaf and bg.pending() and not exit_ignored:  # spike S4: the first /exit after a wakeup is ignored
                        exit_ignored = True
                        continue
                    bg.finish()
                    tr.local_command_exit()
                    sys.exit(0)
                run_turn(tr, message, scenario, flags, bg)
                say(f"{GLYPH} ")


if __name__ == "__main__":
    main()
